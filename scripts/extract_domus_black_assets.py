"""Extract the official Black brochure and model sheets for the NIA landing.

Inputs: Drive PDFs 16OM2mFA5QhqxfxOrFTMIVRWMVLrxWLPt (brochure)
and 1sbQXMJFhaqyOeU0663BAdwh4M0J0FEz4 (isometrics / apartment plans).
No prices or inventory data are generated by this script.
"""
import argparse
import io
import json
from pathlib import Path

import pymupdf
from PIL import Image, ImageOps


FAMILIES = [
    # family, model sheet, brochure image, floor-plan rectangle in that image
    ("a", 1, 456, (505, 12, 726, 220)),
    ("b", 2, 466, (485, 35, 718, 240)),
    ("c", 3, 471, (535, 25, 779, 240)),
    ("d", 4, 487, (460, 10, 681, 240)),
    ("e", 5, 492, (430, 0, 676, 250)),
    ("f", 6, 497, (520, 0, 736, 250)),
    ("g", 7, 509, (500, 30, 726, 280)),
    ("h", 8, 514, (480, 35, 726, 290)),
    ("i", 9, 519, (500, 0, 707, 250)),
    ("j", 10, 531, (450, 0, 667, 270)),
    ("k", 11, 536, (485, 25, 705, 260)),
    ("l", 12, 546, (500, 0, 707, 225)),
    ("m", 13, 541, (505, 0, 712, 260)),
]

SOCIAL_IMAGES = {
    "piscina-interior": 393,  # brochure page 25
    "piscina-exterior": 384,  # page 24
    "saunas": 391,           # page 25
    "gimnasio": 353,         # page 21
    "churrasquera": 335,     # page 19
    "cowork": 366,           # page 22
    "juegos": 364,           # page 22
    "eventos": 324,          # page 18
    "cafeteria": 266,        # page 12
    "lobby": 252,            # page 10
}


def embedded(doc, xref):
    return Image.open(io.BytesIO(doc.extract_image(xref)["image"])).convert("RGB")


def save_jpeg(image, target, quality=92):
    target.parent.mkdir(parents=True, exist_ok=True)
    image.save(target, "JPEG", quality=quality, optimize=True)


def render_page(doc, number, target):
    pix = doc[number - 1].get_pixmap(matrix=pymupdf.Matrix(2.4, 2.4), alpha=False)
    save_jpeg(Image.frombytes("RGB", (pix.width, pix.height), pix.samples), target)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--brochure", required=True, type=Path)
    parser.add_argument("--models", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=Path("frontend/public/domus/domus_black"))
    args = parser.parse_args()
    brochure, models = pymupdf.open(args.brochure), pymupdf.open(args.models)
    assert len(brochure) == 36 and len(models) == 13, "Review a changed PDF before extracting"
    output = args.out

    for family, number, xref, floor_rect in FAMILIES:
        # The isolated high-resolution apartment image keeps the whole balcony
        # and service area, unlike the old crops selected by bedroom count.
        page = models[number - 1]
        iso = next(im for im in page.get_images() if im[2:4] == (1599, 1599))
        image = embedded(models, iso[0])
        save_jpeg(ImageOps.expand(image, border=48, fill="white"), output / "modelos" / f"familia-{family}.jpg")

        # The small floor diagram on brochure pages 32–35 places the family
        # in its floor. Its original highlighted area is preserved.
        floor = embedded(brochure, xref).crop(floor_rect)
        save_jpeg(ImageOps.expand(floor, border=14, fill="white"), output / "planos" / f"familia-{family}.jpg")

        # The complete individual sheet also includes the apartment's 2D plan.
        # It resolves the brochure's E / F / I label inconsistencies without
        # painting over or inventing any labels in the original source.
        pix = page.get_pixmap(matrix=pymupdf.Matrix(2, 2), alpha=False)
        save_jpeg(Image.frombytes("RGB", (pix.width, pix.height), pix.samples), output / "fichas" / f"familia-{family}.jpg")

    for name, xref in SOCIAL_IMAGES.items():
        save_jpeg(embedded(brochure, xref), output / "amenidades" / f"{name}.jpg")

    for name, page in [
        ("alborada-portafolio", 2), ("ubicacion-oficial", 5),
        ("equipamiento-departamentos", 27), ("equipamiento-condominio", 29),
    ]:
        render_page(brochure, page, output / f"{name}.jpg")

    # Keep the complete building silhouette from page 7; omit the obsolete
    # unit-count box and conflicting floor labels, rather than publishing
    # 137 units next to the current inventory of 141.
    original_diagram = embedded(brochure, 209)
    diagram = Image.new("RGB", (525, 748), "white")
    diagram.paste(original_diagram.crop((460, 100, 805, 848)), (180, 0))
    diagram.paste(original_diagram.crop((280, 550, 460, 848)), (0, 450))
    save_jpeg(ImageOps.expand(diagram, border=24, fill="white"), output / "distribucion-edificio.jpg")
    print(json.dumps({"families": len(FAMILIES), "social_images": len(SOCIAL_IMAGES), "output": str(output)}))


if __name__ == "__main__":
    main()
